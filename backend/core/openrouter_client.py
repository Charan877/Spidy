REQUEST_TIMEOUT = 45.0


def get_openrouter_client() -> OpenAI:
    """Create and return an OpenAI-compatible client pointed at OpenRouter."""
    api_key = os.getenv("OPENROUTER_API_KEY")
    if not api_key:
        raise ValueError(
            "OPENROUTER_API_KEY is missing. "
            "Please copy .env.example to .env and set your OPENROUTER_API_KEY."
        )
    return OpenAI(
        api_key=api_key,
        base_url="https://openrouter.ai/api/v1",
        timeout=REQUEST_TIMEOUT,
        max_retries=1,
    )


def is_api_configured() -> bool:
    """Check if either NVIDIA_API_KEY or OPENROUTER_API_KEY is configured."""
    return bool(os.getenv("NVIDIA_API_KEY") or os.getenv("OPENROUTER_API_KEY"))


